def build_fixture(root: Path):
    (root / 'sql').mkdir(parents=True)
    (root / 'src' / 'map').mkdir(parents=True)
    (root / 'src' / 'map' / 'zone.h').write_text(FIXTURE_ZONE_H)

    for name, rows in FIXTURE_SQL.items():
        (root / 'sql' / name).write_text('\n'.join(rows) + '\n')


class ExtractionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        root = Path(cls.tmp.name)
        build_fixture(root)
        cls.data = X.ServerData(root)
        cls.mobs, cls.accounting = X.extract(cls.data)

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def entry(self, zone, name):
        entries = self.mobs[zone][name]
        self.assertEqual(1, len(entries))
        return entries[0]

    def test_war_non_baseline(self):
        # Snipper, WAR/NON, species ranks VIT C / AGI D / DEF C, lvl 20-25.
        # Level 20:
        #   fVIT = 4+(19*40)//100 = 11, mVIT(grade 4) = 3+(19*35)//100 = 9,
        #   sub NON = 0 -> VIT 20
        #   fAGI(D) = 9, mAGI(grade 3) = 11 -> AGI 20
        #   DEF = 8 + 20//2 + floor(5 + 19*2.8)=58 -> 76
        #   EVA: WAR evasion rank 6 -> base rank C -> 58 + 20//2 = 68
        # Level 25:
        #   fVIT = 4+(24*40)//100 = 13, mVIT = 3+(24*35)//100 = 11 -> 24
        #   fAGI = 11, mAGI = 13 -> 24
        #   DEF = 8 + 12 + floor(5 + 24*2.8)=72 -> 92
        #   EVA = 72 + 12 = 84
        e = self.entry(1, 'Snipper')

        self.assertEqual((20, 25), (e['min_level'], e['max_level']))
        self.assertEqual({'vit': 20, 'agi': 20, 'def': 76, 'eva': 68},
                         e['levels'][20])
        self.assertEqual({'vit': 24, 'agi': 24, 'def': 92, 'eva': 84},
                         e['levels'][25])
        self.assertEqual('WAR', e['mjob'])
        self.assertFalse(e['nm'])

    def test_per_level_rows_are_exact(self):
        # Level 21 (an INTERIOR level, must be exact, not interpolated):
        #   fVIT = 4+(20*40)//100 = 12, mVIT = 3+(20*35)//100 = 10 -> VIT 22
        #   fAGI = 3+(20*35)//100 = 10, mAGI = 4+(20*40)//100 = 12 -> AGI 22
        #   DEF = 8 + 22//2 + floor(5 + 20*2.8)=61 -> 80
        #   EVA = 61 + 22//2 = 72
        e = self.entry(1, 'Snipper')

        self.assertEqual(6, len(e['levels']))  # 20..25 inclusive
        self.assertEqual({'vit': 22, 'agi': 22, 'def': 80, 'eva': 72},
                         e['levels'][21])

    def test_spawn_points_deduped(self):
        # Two spawn points of the same group -> one entry (asserted in
        # self.entry via len == 1)
        self.entry(1, 'Snipper')

    def test_subjob_halved_outside_original_zones(self):
        # Sub Crab WAR/WHM @30 in zone 1 (not a subjob zone):
        #   fVIT = 4+(29*40)//100 = 15, mVIT = 3+(29*35)//100 = 13,
        #   sVIT = base_to_rank(WHM grade 4, 30)=13 // 2 = 6 -> VIT 34
        #   fAGI(D) = 13, mAGI = 4+(29*40)//100 = 15,
        #   sAGI = base_to_rank(WHM grade 5, 30)=11 // 2 = 5 -> AGI 33
        #   DEF = 8 + 17 + floor(5+29*2.8)=86 -> 111
        #   EVA: min(WAR 6, WHM 10) -> rank C -> 86 + 16 = 102
        e = self.entry(1, 'Sub Crab')

        self.assertEqual({'vit': 34, 'agi': 33, 'def': 111, 'eva': 102},
                         e['levels'][30])

    def test_subjob_formula_inside_original_zones(self):
        # Same pool in zone 100 (West Ronfaure, subjob zone, sLvl < 50):
        #   sVIT = GetSubJobStats(D, 30, 13) = floor(13/4.55) = 2 -> VIT 30
        #   sAGI = GetSubJobStats(E, 30, 11) = floor(11/(3.8+0.2)) = 2 -> AGI 30
        #   DEF = 8 + 15 + 86 = 109; EVA = 86 + 15 = 101
        e = self.entry(100, 'Sub Crab')

        self.assertEqual({'vit': 30, 'agi': 30, 'def': 109, 'eva': 101},
                         e['levels'][30])

    def test_traits_apply_highest_rank(self):
        # Rock Crab WAR/NIN @30: NIN Evasion Bonus rank 2 (+22) applies.
        #   VIT: 15 + 13 + base_to_rank(NIN grade 3, 30)=15 // 2 = 7 -> 35
        #   AGI: 13 + 15 + base_to_rank(NIN grade 2, 30)=17 // 2 = 8 -> 36
        #   DEF = 8 + 17 + 86 = 111
        #   EVA: min(WAR 6, NIN 1) -> rank A -> floor(6+29*3.0)=93
        #        93 + 36//2 + 22 = 133
        e = self.entry(1, 'Rock Crab')

        self.assertEqual({'vit': 35, 'agi': 36, 'def': 111, 'eva': 133},
                         e['levels'][30])

    def test_species_mods(self):
        # Pool Crab (species 11, +20 EVA species mod) @20: EVA 68 + 20
        e = self.entry(1, 'Pool Crab')

        self.assertEqual(88, e['levels'][20]['eva'])
        self.assertEqual(76, e['levels'][20]['def'])

    def test_pool_mods_and_nm_flag(self):
        # Mod Crab @20: +12 DEF pool mod -> 88; the is_mob_mod=1 row
        # (+99 EVA) must be ignored -> EVA stays 68. mobType bit 2 -> NM.
        e = self.entry(1, 'Mod Crab')

        self.assertEqual(88, e['levels'][20]['def'])
        self.assertEqual(68, e['levels'][20]['eva'])
        self.assertTrue(e['nm'])

    def test_combat_delay_and_h2h(self):
        # mob_pools cmbDelay/cmbSkill feed Telegraph's TP ledger:
        # the fixture POOL_ROW carries cmbSkill 2 / cmbDelay 240
        e = self.entry(1, 'Snipper')

        self.assertEqual(240, e['cmb_delay'])
        self.assertFalse(e['h2h'])

        # cmbSkill 1 = SKILL_HAND_TO_HAND
        fist = self.entry(1, 'Fist Crab')

        self.assertEqual(480, fist['cmb_delay'])
        self.assertTrue(fist['h2h'])

    def test_tp_mods_aggregate_pool_and_species(self):
        # Mod Crab: pool 504 REGAIN 20 + STORETP 10 (is_mob_mod=0),
        # species 10 SUBTLE_BLOW 5; the is_mob_mod=1 REGAIN row is a
        # mobMod and must be ignored
        e = self.entry(1, 'Mod Crab')

        self.assertEqual(
            {'regain': 20, 'store_tp': 10, 'subtle_blow': 5},
            e['tp_mods'])

        # Pool Crab (species 11) has no TP mods at all
        self.assertEqual({}, self.entry(1, 'Pool Crab')['tp_mods'])

    def test_tp_fields_reach_the_lua(self):
        text = X.emit_lua(self.mobs, 'fixture')

        self.assertIn('cmb_delay = 240, h2h = false', text)
        self.assertIn('cmb_delay = 480, h2h = true', text)
        self.assertIn(
            'tp_mods = { regain = 20, store_tp = 10, subtle_blow = 5 }',
            text)
        # entries without TP mods stay lean
        self.assertNotIn('tp_mods = {  }', text)
        self.assertNotIn('tp_mods = { }', text)

    def test_split_emission_balances_across_zones(self):
        with tempfile.TemporaryDirectory() as out:
            out_dir = Path(out) / 'mobs'
            counts = X.emit_split(self.mobs, self.accounting, out_dir,
                                  'fixture')

            # one file per zone + the index
            self.assertEqual({1, 100}, set(counts))
            self.assertTrue((out_dir / 'index.lua').exists())
            self.assertTrue((out_dir / 'zone_1.lua').exists())
            self.assertTrue((out_dir / 'zone_100.lua').exists())

            # index totals must equal extraction accounting
            index_text = (out_dir / 'index.lua').read_text()
            self.assertIn('total_entries = %d'
                          % self.accounting['emitted'], index_text)
            self.assertEqual(self.accounting['emitted'],
                             sum(counts.values()))

            # zone file carries the same exact rows as monolithic mode
            zone1 = (out_dir / 'zone_1.lua').read_text()
            self.assertIn(
                '[21] = { vit = 22, agi = 22, def = 80, eva = 72 }',
                zone1)

    def test_split_raises_on_row_loss(self):
        # Simulate a future bug that drops a zone between extraction
        # and emission: the cross-split conservation check must fire.
        crippled = dict(self.mobs)
        del crippled[100]

        with tempfile.TemporaryDirectory() as out:
            with self.assertRaises(X.ConservationError):
                X.emit_split(crippled, self.accounting,
                             Path(out) / 'mobs', 'fixture')

    def test_singleton_validation_targets(self):
        # Sub Crab in West Ronfaure (zone 100) spawns at exactly 30/30
        zone_names = {'WEST_RONFAURE': 100}
        lines = X.emit_singletons(self.mobs, zone_names)

        self.assertEqual(1, len(lines))
        self.assertIn('Sub Crab', lines[0])
        self.assertIn('Lv.30', lines[0])
        self.assertIn('def=109', lines[0])

    def test_lua_emission_is_loadable_shape(self):
        text = X.emit_lua(self.mobs, 'fixture')

        self.assertIn("['Snipper']", text)
        self.assertIn('[20] = { vit = 20, agi = 20, def = 76, eva = 68 }',
                      text)
        self.assertTrue(text.startswith('-- Generated'))
        self.assertTrue(text.rstrip().endswith('}'))


