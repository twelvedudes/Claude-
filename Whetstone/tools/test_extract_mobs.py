class FormulaTests(unittest.TestCase):
    def test_base_to_rank(self):
        # GetBaseToRank, integer division:
        # C(3) @ 20: 4 + (19 * 40) // 100 = 4 + 7
        self.assertEqual(11, X.base_to_rank(3, 20))
        # A(1) @ 75: 5 + (74 * 50) // 100 = 5 + 37
        self.assertEqual(42, X.base_to_rank(1, 75))
        # G(7) @ 75: 2 + (74 * 20) // 100 = 2 + 14
        self.assertEqual(16, X.base_to_rank(7, 75))
        # invalid rank (NON job grade 0)
        self.assertEqual(0, X.base_to_rank(0, 50))

    def test_base_def_eva(self):
        # C @ 20: floor(5 + 19 * 2.8) = floor(58.2)
        self.assertEqual(58, X.base_def_eva(3, 20))
        # A @ 75: floor(153 + 25 * 5.0)
        self.assertEqual(278, X.base_def_eva(1, 75))
        # B @ 75: floor(147 + 25 * 4.9) = floor(269.5)
        self.assertEqual(269, X.base_def_eva(2, 75))
        # E @ 51: floor(126 + 1 * 4.5)
        self.assertEqual(130, X.base_def_eva(5, 51))

    def test_sub_job_stats(self):
        # D @ 30 with stat 13: max(floor(13 / (5.0 - 0.05*9)), 1)
        #   = floor(13 / 4.55) = 2
        self.assertEqual(2, X.sub_job_stats(4, 30, 13))
        # A @ 75 with stat 42: floor(42 / (2.7 - 0.001*30))
        #   = floor(42 / 2.67) = floor(15.73) = 15
        self.assertEqual(15, X.sub_job_stats(1, 75, 42))

    def test_eva_rank_mapping(self):
        # JobSkillRankToBaseEvaRank: best (lowest) rank wins
        self.assertEqual(1, X.eva_rank_from_skill_ranks(1, 5))
        self.assertEqual(3, X.eva_rank_from_skill_ranks(6, 10))
        self.assertEqual(4, X.eva_rank_from_skill_ranks(9, 9))
        self.assertEqual(5, X.eva_rank_from_skill_ranks(10, 11))
        self.assertEqual(3, X.eva_rank_from_skill_ranks(11, 11))  # fallback

    def test_split_values(self):
        values = X.split_values("1,'O''Kane',NULL,0x1F2D,-2,3.5,'a\\'b'")

        self.assertEqual(
            [1, "O'Kane", None, '0x1F2D', -2, 3.5, "a'b"], values)


