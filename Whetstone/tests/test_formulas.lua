describe('fSTR (player melee)', function()
    -- Tiers: dSTR >= 12 -> +4 | >= 6 -> +6 | >= 1 -> +7 | >= -2 -> +8
    --        >= -7 -> +9 | >= -15 -> +10 | >= -21 -> +12 | else +13
    -- then /4, clamped to [-rank (or -1 at rank 0), rank + 8]

    it('computes interior tiers', function()
        assert.are.equal(6, F.fstr(80, 60, 5))   -- dSTR 20: (20+4)/4
        assert.are.equal(2, F.fstr(60, 60, 5))   -- dSTR 0: (0+8)/4
        assert.are.equal(3, F.fstr(66, 60, 5))   -- dSTR 6: (6+6)/4
    end)

    it('keeps LSB quarter-point fractions (no floor for players)', function()
        assert.are.equal(2.75, F.fstr(64, 60, 5)) -- dSTR 4 -> 11/4
        assert.are.equal(4.25, F.fstr(73, 60, 5)) -- dSTR 13 -> 17/4
    end)

    it('clamps the stat diff window by weapon rank', function()
        -- rank 0: window [-14, 28]. dSTR -30 clamps to -14 -> (-14+10)/4 = -1
        -- which also equals the rank-0 floor of -1
        assert.are.equal(-1, F.fstr(30, 60, 0))
    end)

    it('caps fSTR at rank + 8', function()
        -- rank 10: window [-54, 68]; dSTR 140 clamps to 68 -> 72/4 = 18 = cap
        assert.are.equal(18, F.fstr(200, 60, 10))
    end)

    it('caps fSTR at -rank on the low side', function()
        -- rank 5: dSTR -34 (window edge) -> (-34+13)/4 = -5.25 -> clamp -5
        assert.are.equal(-5, F.fstr(26, 60, 5))
    end)

    it('truncates toward zero with the strict-era integer knob', function()
        -- Matches AirSkyBoat's C++ integer division: dSTR -11 ->
        -- (-11+10)/4 = -0.25 -> 0 (toward zero, NOT floor -1)
        local era = { fstr_integer = true }

        assert.are.equal(0, F.fstr(49, 60, 5, era))
        assert.are.equal(-0.25, F.fstr(49, 60, 5)) -- default keeps fractions
        assert.are.equal(4, F.fstr(73, 60, 5, era)) -- 4.25 -> 4
    end)
end)

