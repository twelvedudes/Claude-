describe('weapon skill damage', function()
    -- Shared scenario:
    --   D 50, fSTR 6, STR 100 with 50% mod -> WSC 50, alpha 0.83
    --   mainBase = floor(50 + 6 + 50 * 0.83) = floor(97.5) = 97
    --   attack 600 vs defense 300 -> wRatio 2 -> E[pDIF] = 2.00645751953125
    --   (great axe and axe both leave the 2.375 upper bound uncapped)
    --   acc = eva -> base 75%; first hit +100 acc -> capped
    local EPDIF = 2.00645751953125

    local function scenario(overrides)
        local p =
        {
            weapon_dmg     = 50,
            fstr           = 6,
            stats          = { str = 100 },
            ws             = { ftp = { 1.0, 1.5, 2.0 }, num_hits = 2, mods = { str = 0.5 } },
            tp             = 1000,
            attack         = 600,
            defense        = 300,
            acc            = 300,
            eva            = 300,
            attacker_level = 75,
            target_level   = 75,
            alpha          = 0.83,
            weapon         = 'great_axe',
            profile        = 'lsb', -- keep modern caps so EPDIF stays uncapped
        }

        for key, value in pairs(overrides or {}) do
            p[key] = value
        end

        return p
    end

    it('builds mainBase = floor(D + fSTR + WSC * alpha)', function()
        local r = F.ws_damage(scenario())

        assert.are.equal(50, r.wsc)
        assert.are.equal(97, r.main_base)
    end)

    it('gives the first hit +100 accuracy and caps by weapon class', function()
        local r = F.ws_damage(scenario())

        -- 2H: raw (75 + 50)% caps at 95%; extra hits stay at 75%
        assert.are.equal(0.95, r.first_hit_rate)
        assert.are.equal(0.75, r.extra_hit_rate)
    end)

    it('computes a two-hit 2H weapon skill', function()
        -- E = 97 * 1.0 * EPDIF * 0.95  (first)
        --   + 97 * 1.0 * EPDIF * 0.75  (second, fTP reset to 1)
        local r = F.ws_damage(scenario())

        assert.near(97 * EPDIF * (0.95 + 0.75), r.expected, 1e-9)
        assert.are.equal(2, r.swings)
    end)

    it('applies fTP only to the first hit by default', function()
        -- TP 3000 -> fTP 2.0 on first hit only
        local r = F.ws_damage(scenario({ tp = 3000 }))

        assert.near(97 * EPDIF * (2.0 * 0.95 + 1.0 * 0.75), r.expected, 1e-9)
    end)

    it('carries fTP to all hits when multi_hit_ftp is set', function()
        local r = F.ws_damage(scenario(
        {
            tp = 3000,
            ws = { ftp = { 1.0, 1.5, 2.0 }, num_hits = 2, mods = { str = 0.5 }, multi_hit_ftp = true },
        }))

        assert.near(97 * EPDIF * 2.0 * (0.95 + 0.75), r.expected, 1e-9)
    end)

    it('adds an unfloored offhand hit at the 95% cap', function()
        -- 1H axe, 1 hit + offhand:
        --   offhandBase = 30 + 6 + 41.5 = 77.5 (NOT floored)
        --   first hit cap 0.99 (1H main), offhand 75% raw
        local r = F.ws_damage(scenario(
        {
            weapon      = 'axe',
            offhand_dmg = 30,
            ws          = { ftp = { 1.0, 1.5, 2.0 }, num_hits = 1, mods = { str = 0.5 } },
        }))

        assert.near(77.5, r.offhand_base, 1e-12)
        assert.are.equal(0.99, r.first_hit_rate)
        assert.are.equal(0.75, r.offhand_hit_rate)
        assert.near(EPDIF * (97 * 0.99 + 77.5 * 0.75), r.expected, 1e-9)
        assert.are.equal(2, r.swings)
    end)

    it('applies the WS attack multiplier to pDIF', function()
        -- atk_varies 2.0: attack 300 vs def 300 -> wRatio 2
        local r = F.ws_damage(scenario(
        {
            attack = 300,
            ws     = { ftp = { 1.0, 1.5, 2.0 }, num_hits = 1, mods = { str = 0.5 }, atk_varies = 2.0 },
        }))

        assert.near(2.0, r.pdif.wratio, 1e-12)
    end)

    it('only crits when crit_varies is present', function()
        local plain = F.ws_damage(scenario())

        assert.are.equal(0, plain.crit_rate)
        assert.is_nil(plain.pdif_crit)

        local crit = F.ws_damage(scenario(
        {
            tp         = 2000,
            stats      = { str = 100, dex = 80 },
            target_agi = 60,
            ws         =
            {
                ftp         = { 1.0, 1.5, 2.0 },
                num_hits    = 1,
                mods        = { str = 0.5 },
                crit_varies = { 0.1, 0.25, 0.5 },
            },
        }))

        -- 0.05 base + 0.03 dDEX(20) + 0.25 TP factor
        assert.near(0.33, crit.crit_rate, 1e-12)
        assert.near(
            0.67 * crit.pdif.expected + 0.33 * crit.pdif_crit.expected,
            crit.expected_pdif, 1e-12)
    end)

    it('adds H2H natural damage to both hands', function()
        -- h2h_skill 100 -> natural 14; D 10 + 14 = 24 per hand
        -- mainBase = floor(24 + 2) = 26, offhandBase = 26
        local r = F.ws_damage(
        {
            weapon_dmg     = 10,
            offhand_dmg    = 0, -- ignored: H2H mirrors the main hand
            h2h_skill      = 100,
            fstr           = 2,
            stats          = {},
            ws             = { num_hits = 1, mods = {} },
            tp             = 1000,
            attack         = 600,
            defense        = 300,
            acc            = 300,
            eva            = 300,
            attacker_level = 75,
            target_level   = 75,
            alpha          = 0.83,
            profile        = 'lsb',
        })

        assert.are.equal(26, r.main_base)
        assert.near(26, r.offhand_base, 1e-12)
        -- H2H uses the 99% ceiling (lsb profile)
        assert.are.equal(0.99, r.first_hit_rate)
    end)

    it('selects WSC alpha from the profile', function()
        local base =
        {
            weapon_dmg     = 50,
            fstr           = 6,
            stats          = { str = 100 },
            ws             = { ftp = { 1.0, 1.5, 2.0 }, num_hits = 1, mods = { str = 0.5 } },
            tp             = 1000,
            attack         = 600,
            defense        = 300,
            acc            = 300,
            eva            = 300,
            attacker_level = 75,
            target_level   = 75,
            weapon         = 'great_axe',
        }

        -- Phoenix (default): legacy alpha(75) = 0.83
        --   mainBase = floor(50 + 6 + 50 * 0.83) = 97
        local phoenix = F.ws_damage(base)

        assert.near(0.83, phoenix.alpha, 1e-12)
        assert.are.equal(97, phoenix.main_base)

        -- lsb: Adoulin rules, alpha = 1
        --   mainBase = floor(50 + 6 + 50) = 106
        base.profile = 'lsb'
        local lsb = F.ws_damage(base)

        assert.near(1, lsb.alpha, 1e-12)
        assert.are.equal(106, lsb.main_base)
    end)

    it('caps Phoenix WS pDIF at the era 2.0 ceiling', function()
        -- Same scenario under the phoenix profile: wRatio 2 great axe
        -- E[pDIF] = (1.5400390625 + 2.0)/2 * 1.025 = 1.81427001953125
        -- 2H hit caps are 0.95 under both profiles, so only pDIF moves.
        local r = F.ws_damage(scenario({ profile = 'phoenix' }))

        assert.near(1.81427001953125, r.expected_pdif, 1e-12)
        assert.near(97 * 1.81427001953125 * (0.95 + 0.75), r.expected, 1e-9)
    end)

    it('caps total swings at 8', function()
        local r = F.ws_damage(scenario(
        {
            weapon      = 'axe',
            offhand_dmg = 30,
            ws          = { ftp = { 1.0, 1.5, 2.0 }, num_hits = 8, mods = { str = 0.5 } },
        }))

        assert.are.equal(8, r.swings)
    end)
end)

